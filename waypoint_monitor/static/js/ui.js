const STEPS_VIEW_KEY = 'wp-steps-view';
let stepsView = 'graph';
try {
  const saved = localStorage.getItem(STEPS_VIEW_KEY);
  if (saved === 'list' || saved === 'graph') stepsView = saved;
} catch (e) {
  /* storage unavailable: default view */
}
export const getStepsView = () => stepsView;
export function setStepsView(v) {
  stepsView = v === 'list' ? 'list' : 'graph';
  try {
    localStorage.setItem(STEPS_VIEW_KEY, stepsView);
  } catch (e) {
    /* storage unavailable: the choice just won't persist */
  }
}

