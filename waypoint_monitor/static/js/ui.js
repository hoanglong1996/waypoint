/* ---------- change chip (vs previous run) ---------- */
export function deltaChip(cur, prev, opts = {}) {
  const d = deltaPct(cur, prev);
  if (d.kind === 'none') return '';
  if (d.kind === 'flat') return '<span class="delta delta--flat">' + I.flat + '0%</span>';
  if (d.kind === 'new') return '<span class="delta delta--up">' + I.up + 'new</span>';
  const r = d.pct;
  const cls = r > 0 ? 'up' : 'down';
  const ico = r > 0 ? I.up : I.down;
  const txt = (r > 0 ? '+' : '−') + Math.abs(r).toFixed(Math.abs(r) >= 10 ? 0 : 1) + '%';
  const sr = (r > 0 ? 'up ' : 'down ') + Math.abs(r).toFixed(1) + ' percent';
  return (
    '<span class="delta delta--' + cls + '" title="vs previous run (' + fmt(prev) + ')">' + ico +
    '<span aria-hidden="true">' + txt + '</span><span class="sr-only">' + sr + (opts.label ? ' ' + opts.label : ' vs previous run') + '</span></span>'
  );
}

